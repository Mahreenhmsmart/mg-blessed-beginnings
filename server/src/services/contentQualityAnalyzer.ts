      // Title and H1 alignment
      const titleWords = title.toLowerCase().split(/\s+/).filter((w) => w.length > 3);
      const h1Words = h1.toLowerCase().split(/\s+/).filter((w) => w.length > 3);
      const overlap = titleWords.filter((w) => h1Words.includes(w)).length;
      const hasTitleH1Alignment = overlap >= Math.min(titleWords.length, h1Words.length) * 0.4;

      // Meta description provides summary
      const hasGoodMeta = metaDesc.length >= 100 && metaDesc.length <= 200;

      let score = 0;
      const signals: string[] = [];

      if (hasEarlyAnswer) { signals.push('early content summary'); score += 3; }
      if (hasTitleH1Alignment) { signals.push('title/H1 alignment'); score += 3; }
      if (hasGoodMeta) { signals.push('descriptive meta'); score += 2; }

      if (score >= 6) {
        return { status: 'pass', points: 8, details: `Good intent alignment: ${signals.join(', ')}.` };
      }
      if (score >= 3) {
        return { status: 'warn', points: 4, details: `Partial alignment: ${signals.join(', ')}. Add a clear answer near the top.` };
      }
      return { status: 'warn', points: 1, details: 'Weak intent alignment. Ensure title, H1, and opening paragraph address the same topic clearly.' };
