/**
 * Content Quality Analyzer — Evaluates crawled page content against Google's
 * people-first content and E-E-A-T guidelines. Returns LayerResults with
 * individual checks and a normalized 0-100 score.
 */

import type { CrawlResult } from './crawlerService';
import type { CheckResult, LayerResults } from '../models/Audit';

interface CqCheck {
  id: string;
  name: string;
  category: 'content' | 'eeat' | 'people-first';
  maxPoints: number;
  evaluate: (crawl: CrawlResult) => { status: 'pass' | 'warn' | 'fail'; points: number; details: string };
}

// ─── Helper utilities ────────────────────────────────────────────────────────

function countWords(text: string): number {
  return text.split(/\s+/).filter(Boolean).length;
}

function getTextToHtmlRatio(html: string, visibleText: string): number {
  const htmlLen = html.length;
  const textLen = visibleText.length;
  if (htmlLen === 0) return 0;
  return Math.round((textLen / htmlLen) * 100);
}

function estimateKeywordDensity(text: string, keywords: string[]): number {
  if (keywords.length === 0 || text.length === 0) return 0;
  const lower = text.toLowerCase();
  const words = lower.split(/\s+/).filter(Boolean);
  const totalWords = words.length;
  if (totalWords === 0) return 0;
  let matchCount = 0;
  for (const kw of keywords) {
    const kwLower = kw.toLowerCase();
    matchCount += words.filter((w) => w.includes(kwLower)).length;
  }
  return Math.round((matchCount / totalWords) * 10000) / 100; // percentage to 2dp
}

function hasFirstPersonLanguage(text: string): boolean {
  const patterns = [/\bI\b/, /\bmy\b/, /\bwe\b/, /\bour\b/, /\bme\b/, /\bpersonally\b/, /\bin my experience\b/i];
  return patterns.some((p) => p.test(text));
}

function hasDataOrStatistics(text: string): boolean {
  const patterns = [/\d+\s*%/, /\d+\s*(studies|research|survey|report|statistics|data)/i, /\baccording to\b/i, /\bresearch shows\b/i, /\bstudy found\b/i, /\b\d{4}\b/];
  return patterns.some((p) => p.test(text));
}

function detectAuthorByline(html: string): boolean {
  const patterns = [/class=["'][^"']*author[^"']*["']/i, /rel=["']author["']/i, /itemprop=["']author["']/i, /by\s+[A-Z][a-z]+/i, /written by/i, /author:/i];
  return patterns.some((p) => p.test(html));
}

function detectPublicationDate(html: string): boolean {
  const patterns = [/<time[^>]*datetime=/i, /datePublished/i, /publish_date/i, /article:published_time/i, /class=["'][^"']*date[^"']*["']/i, /class=["'][^"']*published[^"']*["']/i];
  return patterns.some((p) => p.test(html));
}

function detectLastUpdated(html: string): boolean {
  const patterns = [/dateModified/i, /last[_-]?updated/i, /modified[_-]?date/i, /updated[_-]?on/i, /last revised/i];
  return patterns.some((p) => p.test(html));
}

function hasExternalAuthorityLinks(crawl: CrawlResult): boolean {
  const authorityDomains = ['wikipedia.org', 'gov', '.edu', 'scholar.google', 'nih.gov', 'who.int', 'statista.com', 'pewresearch.org'];
  return crawl.externalLinks.some((link) => authorityDomains.some((d) => link.includes(d)));
}

function detectStructuredData(crawl: CrawlResult): boolean {
  return crawl.structuredData.length > 0 || crawl.hasFaqSchema || crawl.hasBreadcrumbSchema || crawl.hasOrganizationSchema || crawl.hasPersonSchema;
}

function detectContactInfo(html: string): boolean {
  const patterns = [/mailto:/i, /tel:/i, /contact[-_]?us/i, /support@/i, /phone/i, /class=["'][^"']*contact[^"']*["']/i];
  return patterns.some((p) => p.test(html));
}

function detectSocialProof(html: string): boolean {
  const patterns = [/testimonial/i, /review/i, /rating/i, /stars?/i, /customer\s+stor/i, /trustpilot/i, /google\s+reviews/i, /yelp/i];
  return patterns.some((p) => p.test(html));
}

function detectAIDisclosure(html: string, text: string): boolean {
  const combined = html + ' ' + text;
  const patterns = [/ai[\s-]?(generated|written|assisted|powered)/i, /written by ai/i, /generated by/i, /chatgpt/i, /automatically generated/i, /machine[\s-]?generated/i, /editorial process/i, /fact[\s-]?checked/i, /human[\s-]?reviewed/i];
  return patterns.some((p) => p.test(combined));
}

function detectOutdatedContent(text: string): boolean {
  const currentYear = new Date().getFullYear();
  const yearPattern = /\b(20[01]\d|202[0-3])\b/g;
  const matches = text.match(yearPattern);
  if (!matches) return false;
  const oldYears = matches.filter((y) => parseInt(y) < currentYear - 2);
  return oldYears.length >= 2;
}

function detectCookieConsent(html: string): boolean {
  const patterns = [/cookie[\s-]?(consent|banner|notice|policy|accept)/i, /gdpr/i, /privacy[\s-]?consent/i, /cookie[\s-]?bar/i, /consent[\s-]?manager/i];
  return patterns.some((p) => p.test(html));
}

function detectTocOrJumpLinks(html: string): boolean {
  const patterns = [/table[\s-]?of[\s-]?contents/i, /toc/i, /jump[\s-]?to/i, /#[\w-]+/g, /id=["']toc["']/i, /class=["'][^"']*toc[^"']*["']/i];
  return patterns.some((p) => p.test(html));
}

function detectCTAs(html: string): boolean {
  const patterns = [/<button/i, /cta/i, /call[\s-]?to[\s-]?action/i, /get\s+started/i, /learn\s+more/i, /sign\s+up/i, /subscribe/i, /download/i, /buy\s+now/i, /free\s+trial/i];
  return patterns.some((p) => p.test(html));
}

